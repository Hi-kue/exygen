from __future__ import annotations

import re

from exygen_agent.llm_client import BaseLLMClient, get_llm_client
from exygen_agent.synthesis_contracts import (
    AnchorQuestion,
    BlueprintSlot,
    CorrectnessStatus,
    CriticEvaluation,
    MarkdownParseError,
    SynthesizedQuestion,
    extract_markdown_sections,
)

CRITIC_KNOWN_HEADERS = {
    "ACCEPTED",
    "CORRECTNESS_STATUS",
    "CODE_SANDBOX_PASSED",
    "STYLE_ALIGNMENT_SCORE",
    "ISSUES",
    "VERIFIER_NOTES",
    "NOTES",
}

AFFIRMATIVE_TOKENS = {"true", "yes", "1", "pass", "passed", "accepted", "accept", "verified"}
NEGATIVE_TOKENS = {"false", "no", "0", "fail", "failed", "rejected", "reject", "flagged"}
NA_TOKENS = {"n/a", "na", "none", "null", "not_applicable", "not applicable", ""}

SYSTEM_PROMPT = """You are Agent 3 (Critic / Verifier Interface) for Exygen, an advanced AI application that crafts instructor-aligned Computer Science practice exams.

Your role is to rigorously evaluate a candidate practice exam question generated by Agent 2.
You act as an exacting academic reviewer and teaching assistant verifying question correctness, solvability, and instructor style alignment.

CRITICAL INSTRUCTIONS:
1. Do NOT output JSON. Use exact Markdown section headers.
2. You MUST structure your response with the following Markdown headers:
   ## ACCEPTED
   [REQUIRED. Write true or false]

   ## CORRECTNESS_STATUS
   [verified or flagged or unverified]

   ## CODE_SANDBOX_PASSED
   [true or false for code_writing questions; write N/A when not applicable]

   ## STYLE_ALIGNMENT_SCORE
   [A float between 0.0 and 1.0, e.g., 0.92]

   ## ISSUES
   [List each specific defect or inaccuracy as a bullet point starting with '-', or write 'None']

   ## VERIFIER_NOTES
   [REQUIRED. Detailed evaluation explaining why the question was accepted or rejected, verifying the step-by-step trace or math, and assessing alignment with the instructor anchor]

3. Acceptance Criteria:
   - Mark ACCEPTED as false if:
     * There is any mathematical or algorithmic error in the question or solution.
     * For MCQ, the correct choice does not match the explanation or there are multiple ambiguous correct answers.
     * The question copies the anchor verbatim or is trivially identical.
     * The difficulty wildly diverges from the target slot.
   - Mark ACCEPTED as true ONLY when the question is mathematically/algorithmically sound, unambiguous, properly paced, and matches course standards."""


def build_critic_prompt(
    slot: BlueprintSlot,
    anchor: AnchorQuestion,
    question: SynthesizedQuestion,
) -> str:
    """Builds the evaluation prompt for Agent 3."""
    options_str = "N/A (Not Multiple Choice)"
    if question.mcq_options:
        options_str = "\n".join(f"({k}) {v}" for k, v in question.mcq_options.items())

    test_cases_str = question.code_test_cases or "None (N/A)"

    return f"""### TARGET SLOT CONSTRAINTS:
- Slot: #{slot.slot_number} | Topic: {slot.topic} | Format: {slot.format} | Marks: {slot.target_marks} | Difficulty: {slot.difficulty}

### EXEMPLAR ANCHOR CONTEXT:
- Anchor ID: {anchor.question_id}
- Archetype: {anchor.archetype}
- Anchor Raw Text:
\"\"\"
{anchor.raw_text.strip()}
\"\"\"

### CANDIDATE QUESTION TO EVALUATE:
- Prompt:
\"\"\"
{question.prompt}
\"\"\"

- Options:
{options_str}

- Solution:
{question.solution}

- Explanation:
{question.explanation}

- Code Test Cases / Sandboxing:
{test_cases_str}

- Author Rationale:
{question.rationale}

Please provide your rigorous academic verification using the specified Markdown section headers."""


def _parse_flexible_bool(raw: str) -> bool | None:
    """Flexibly parses boolean values from LLM Markdown text (e.g. '**true**', 'Yes, accepted', 'N/A')."""
    cleaned = re.sub(r"[*_`\[\]\(\)]", "", raw).strip().lower()
    if cleaned in NA_TOKENS:
        return None
    if cleaned in AFFIRMATIVE_TOKENS:
        return True
    if cleaned in NEGATIVE_TOKENS:
        return False

    # Inspect the first token (e.g., "true - trace verified" or "no, the index is wrong")
    first_token_match = re.match(r"^([a-z0-9/]+)", cleaned)
    if first_token_match:
        token = first_token_match.group(1)
        if token in NA_TOKENS:
            return None
        if token in AFFIRMATIVE_TOKENS:
            return True
        if token in NEGATIVE_TOKENS:
            return False

    # Fallback: check word boundaries anywhere in a short single-line verdict
    words = re.findall(r"\b[a-z0-9/]+\b", cleaned)
    for w in words:
        if w in AFFIRMATIVE_TOKENS:
            return True
        if w in NEGATIVE_TOKENS:
            return False

    return None


def parse_critic_markdown(text: str, slot: BlueprintSlot) -> CriticEvaluation:
    """Parses Agent 3's Markdown response into a typed CriticEvaluation.

    Raises MarkdownParseError if mandatory sections (## ACCEPTED, ## VERIFIER_NOTES)
    are missing or unparseable.
    """
    sections = extract_markdown_sections(text, CRITIC_KNOWN_HEADERS)

    accepted_raw = sections.get("ACCEPTED", "").strip()
    notes = (sections.get("VERIFIER_NOTES") or sections.get("NOTES") or "").strip()

    missing: list[str] = []
    if not accepted_raw:
        missing.append("## ACCEPTED")
    if not notes:
        missing.append("## VERIFIER_NOTES")

    if missing:
        raise MarkdownParseError(
            f"Critic response is missing mandatory section(s): {', '.join(missing)}.",
            missing_sections=missing,
        )

    accepted_parsed = _parse_flexible_bool(accepted_raw)
    if accepted_parsed is None:
        raise MarkdownParseError(
            f"Could not parse boolean verdict from ## ACCEPTED: '{accepted_raw}'.",
            missing_sections=["## ACCEPTED"],
        )
    accepted = accepted_parsed

    # Parse CORRECTNESS_STATUS
    status_raw = re.sub(r"[*_`]", "", sections.get("CORRECTNESS_STATUS", "")).strip().lower()
    status: CorrectnessStatus = "verified" if accepted else "flagged"
    for candidate_status in ("verified", "flagged", "unverified"):
        if candidate_status in status_raw.split():
            status = candidate_status  # type: ignore[assignment]
            break

    # Parse CODE_SANDBOX_PASSED (None when N/A or omitted)
    sandbox_raw = sections.get("CODE_SANDBOX_PASSED", "").strip()
    sandbox_passed = _parse_flexible_bool(sandbox_raw)

    # Parse STYLE_ALIGNMENT_SCORE
    score_raw = sections.get("STYLE_ALIGNMENT_SCORE", "").strip()
    score = 0.85 if accepted else 0.45
    score_match = re.search(r"(\d+(?:\.\d+)?)", score_raw)
    if score_match:
        try:
            parsed = float(score_match.group(1))
            score = max(0.0, min(1.0, parsed))
        except ValueError:
            pass

    # Parse ISSUES
    issues_raw = sections.get("ISSUES", "").strip()
    issues: list[str] = []
    if issues_raw and issues_raw.lower() not in {"none", "n/a", "null", "no issues", "none."}:
        for line in issues_raw.splitlines():
            line_clean = line.strip().lstrip("-*•").strip()
            if line_clean and line_clean.lower() not in {"none", "n/a", "no issues", "none."}:
                issues.append(line_clean)

    return CriticEvaluation(
        slot_number=slot.slot_number,
        accepted=accepted,
        correctness_status=status,
        code_sandbox_passed=sandbox_passed,
        style_alignment_score=score,
        issues=issues,
        verifier_notes=notes,
        raw_markdown=text,
    )


class CriticAgent:
    """Agent 3: Evaluates question candidate for correctness, solvability, and style alignment."""

    def __init__(self, llm_client: BaseLLMClient | None = None, model: str | None = None) -> None:
        self.llm_client = llm_client or get_llm_client()
        self.model = model

    def evaluate(
        self,
        slot: BlueprintSlot,
        anchor: AnchorQuestion,
        question: SynthesizedQuestion,
    ) -> CriticEvaluation:
        prompt = build_critic_prompt(slot=slot, anchor=anchor, question=question)
        response_text = self.llm_client.complete(
            prompt=prompt,
            system_prompt=SYSTEM_PROMPT,
            model=self.model,
        )
        return parse_critic_markdown(response_text, slot)
